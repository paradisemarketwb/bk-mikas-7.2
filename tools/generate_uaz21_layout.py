#!/usr/bin/env python3
"""Generate a portable geometry contract from the supplied design, no runtime JSON."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
spec=json.loads((ROOT/'design/uaz21/layout/layout_480.json').read_text())
lines=['/* Generated by tools/generate_uaz21_layout.py; source design/uaz21/layout/layout_480.json. */','#pragma once','#include <stdint.h>','typedef struct { int16_t x,y,w,h,font_px; } bk_uaz_box_t;']
for screen in spec['screens']:
 name=screen['id'][3:].upper()
 for e in screen['elements']:
  ident='BK_UAZ_'+name+'_'+e['id'].upper()
  lines.append('static const bk_uaz_box_t '+ident+' = {'+','.join(str(e[k]) for k in ('x','y','w','h','font_px'))+'};')
(ROOT/'firmware/components/ui_config/include/bk_uaz_layout.h').write_text('\n'.join(lines)+'\n')
